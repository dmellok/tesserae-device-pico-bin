#
# bigstack.py: give the firmware a stack big enough for a TLS handshake.
#
# The Pico SDK defaults to PICO_STACK_SIZE 0x800 -- 2 KB -- placed at the top of
# SCRATCH_Y, a 4 KB bank. That is generous for blinking an LED and nowhere near
# enough for mbedTLS: a TLS 1.2 handshake wants 8-16 KB, because the certificate
# parse and the ECDHE/ECDSA maths are deeply recursive and keep sizeable
# temporaries on the stack.
#
# The failure this fixes is a nasty one to read. On device, the relay handshake
# died in mbedtls_x509_crt_parse_der with MBEDTLS_ERR_MPI_ALLOC_FAILED, while:
#
#   - the received certificate bytes were byte-identical to what the server sent
#     (recovered from a level-4 trace and diffed against openssl output),
#   - the very same bytes parsed correctly on device from a shallow call chain,
#   - a host build of the identical mbedtls_config.h parsed and verified them,
#   - and 365 KB of heap was free, with the allocator wrapper never firing once.
#
# Because it was never an allocation failure. mbedtls_mpi_grow() returns
# MPI_ALLOC_FAILED both when calloc fails AND when the requested limb count
# exceeds MBEDTLS_MPI_MAX_LIMBS -- and a smashed stack turns a sane length field
# into an absurd one. The handshake runs from the cyw43 interrupt, underneath
# lwIP and altcp, which is several frames deeper than the isolated parse; that
# depth difference is the whole bug.
#
# Raising PICO_STACK_SIZE alone cannot fix it: anything over 4 KB overflows
# SCRATCH_Y. So the stack moves to the top of main RAM, where the heap (growing
# up from __end__) and the stack (growing down from the top) meet in the middle
# -- the conventional layout, and one that costs a few KB of heap ceiling out of
# 365 KB free.
#
# SCRATCH_Y's reservation is left alone: it is only 2 KB, core1 and a few SDK
# pieces reference the region, and reclaiming it is not worth the risk.
#
Import("env")
import re
from os.path import join, basename

# 16 KB. Measured need for a TLS 1.2 handshake with a P-256 chain is well under
# this, but stack exhaustion corrupts memory silently rather than failing
# cleanly, so the margin is deliberate. Still under 4% of RAM.
STACK_SIZE = 16 * 1024

src = env.subst("$LDSCRIPT_PATH")
if not src or not src.endswith(".ld"):
    print("bigstack: no LDSCRIPT_PATH to patch; leaving the stack alone")
else:
    with open(src) as f:
        ld = f.read()

    # The SDK puts the stack at the top of SCRATCH_Y and lets the heap run to
    # the very end of RAM. Move the stack to the top of RAM and stop the heap
    # below it. __StackLimit is the SDK's (poorly named) maximum heap pointer.
    subs = [
        (r"__HeapLimit\s*=\s*ORIGIN\(RAM\)\s*\+\s*LENGTH\(RAM\)\s*;",
         "__HeapLimit = ORIGIN(RAM) + LENGTH(RAM) - %d;" % STACK_SIZE),
        (r"__StackLimit\s*=\s*ORIGIN\(RAM\)\s*\+\s*LENGTH\(RAM\)\s*;",
         "__StackLimit = ORIGIN(RAM) + LENGTH(RAM) - %d;" % STACK_SIZE),
        (r"__StackTop\s*=\s*ORIGIN\(SCRATCH_Y\)\s*\+\s*LENGTH\(SCRATCH_Y\)\s*;",
         "__StackTop = ORIGIN(RAM) + LENGTH(RAM);"),
        (r"__StackBottom\s*=\s*__StackTop\s*-\s*SIZEOF\(\.stack_dummy\)\s*;",
         "__StackBottom = __StackTop - %d;" % STACK_SIZE),
    ]
    missing = [p for p, _ in subs if not re.search(p, ld)]
    if missing:
        # Fail loudly. Silently linking with a 2 KB stack is exactly the
        # situation this script exists to prevent, and it does not announce
        # itself -- it corrupts memory under load.
        raise Exception(
            "bigstack: %s does not match the expected SDK layout (%d pattern(s) "
            "not found). The linker script changed; re-check it before building, "
            "because falling back to the default 2 KB stack breaks TLS in a way "
            "that looks like anything but a stack problem." % (basename(src), len(missing)))

    for pat, rep in subs:
        ld = re.sub(pat, rep, ld)

    out = join(env.subst("$BUILD_DIR"), "memmap_bigstack.ld")
    with open(out, "w") as f:
        f.write("/* GENERATED by scripts/bigstack.py from %s -- do not edit. */\n"
                % basename(src))
        f.write(ld)

    # The picosdk builder expands the script path into LINKFLAGS as a literal
    # string, so replacing LDSCRIPT_PATH alone silently does nothing -- the link
    # still uses the SDK's copy. Rewrite the flag itself, and keep
    # LDSCRIPT_PATH in step for anything that reads it.
    env.Replace(LDSCRIPT_PATH=out)
    flags = env.get("LINKFLAGS", [])
    patched = 0
    for i, f in enumerate(flags):
        if isinstance(f, str) and f == src:
            flags[i] = out
            patched += 1
    env.Replace(LINKFLAGS=flags)
    if not patched:
        raise Exception(
            "bigstack: generated %s but could not find the original script in "
            "LINKFLAGS to replace, so the link would silently keep the 2 KB "
            "stack. Check how the picosdk builder passes the linker script."
            % basename(out))

    print("bigstack: stack moved to the top of RAM, %d bytes (was 2048 in SCRATCH_Y)"
          % STACK_SIZE)
